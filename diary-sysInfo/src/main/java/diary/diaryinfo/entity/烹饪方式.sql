CREATE TABLE `cook_way` (
    `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `name` varchar(50) NOT NULL COMMENT '烹饪方式名称',
    `description` varchar(255) DEFAULT NULL COMMENT '描述',
    `user_id` bigint(20) NOT NULL COMMENT '创建人ID',
    `sort_order` int(11) NOT NULL DEFAULT 999 COMMENT '排序字段，数字越小越靠前',
    `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_sort_order` (`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='烹饪方式表';

